def cosine_similarity(vec1, vec2):
    """Calculate cosine similarity between two sparse vectors.

    Args:
        vec1: Dictionary {dimension: value}
        vec2: Dictionary {dimension: value}

    Returns:
        Float between -1 and 1 (typically 0 to 1 for text/count vectors)

    (Generated by claude 2025-11-19, from the prompt 'write a python
    function for the cosine of two sparse vectors, each represented as
    a dictionary')
    """
    # Compute dot product (only for shared dimensions)
    dot_product = sum(vec1[key] * vec2[key] for key in vec1 if key in vec2)

    # Compute magnitudes
    magnitude1 = sum(val ** 2 for val in vec1.values()) ** 0.5
    magnitude2 = sum(val ** 2 for val in vec2.values()) ** 0.5

    # Handle zero vectors
    if magnitude1 == 0 or magnitude2 == 0:
        return 0.0

    return dot_product / (magnitude1 * magnitude2)

def index_of_max(numbers, starter=-1000000):
    best = starter
    best_i = None
    for i, n in enumerate(numbers):
        if n > best:
            best = n
            best_i = i
    return best_i

def cluster_psalms_main():

    psalms = TextCollection("kj")["Psalms"]

    psalms_tf_idf = psalms.all_chapter_tf_idf()

    similarity_matrix = [
        [
            round(cosine_similarity(a, b), 2) if i != j else 0
            for j, b in enumerate(psalms_tf_idf, start=1)
        ]
        for i, a in enumerate(psalms_tf_idf, start=1)
    ]

    for i, row in enumerate(similarity_matrix, start=1):
        print(i, index_of_max(row) + 1)

if __name__ == "__main__":
    cluster_psalms_main()
